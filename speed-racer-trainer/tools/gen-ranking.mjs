// Generates site/js/ranking.js: hand orderings used to build "top X%" ranges.
// SHOVE_ORDER: by equity vs a random hand. CALL_ORDER: by equity vs a top-25% shoving range.
import { writeFileSync } from 'node:fs';
import { evalCards, combosOfClass, rangeFromPct, makeSampler, mulberry32, CLASS_NAMES } from '../site/js/poker.js';

const rng = mulberry32(12345);
const ITERS = +process.argv[2] || 30000;
const cs = new Int32Array(7), vs = new Int32Array(7);
function equity(idx, villainSampler) {
  const combos = combosOfClass(idx);
  let w = 0;
  const dead = new Uint8Array(52);
  for (let it = 0; it < ITERS; it++) {
    const [a, b] = combos[it % combos.length];
    dead.fill(0); dead[a] = dead[b] = 1;
    let v;
    if (villainSampler) v = villainSampler(dead, rng);
    else { do { v = [Math.floor(rng() * 52), Math.floor(rng() * 52)]; } while (v[0] === v[1] || dead[v[0]] || dead[v[1]]); }
    dead[v[0]] = dead[v[1]] = 1;
    let k = 2;
    cs[0] = a; cs[1] = b; vs[0] = v[0]; vs[1] = v[1];
    while (k < 7) { const c = Math.floor(rng() * 52); if (dead[c]) continue; dead[c] = 1; cs[k] = vs[k] = c; k++; }
    const h = evalCards(cs, 7), x = evalCards(vs, 7);
    w += h > x ? 1 : h === x ? 0.5 : 0;
  }
  return w / ITERS;
}
const eqRand = [];
for (let i = 0; i < 169; i++) eqRand.push(equity(i, null));
const shoveOrder = [...Array(169).keys()].sort((a, b) => eqRand[b] - eqRand[a]);
const sampler = makeSampler(rangeFromPct(shoveOrder, 25));
const eqTop = [];
for (let i = 0; i < 169; i++) eqTop.push(equity(i, sampler));
const callOrder = [...Array(169).keys()].sort((a, b) => eqTop[b] - eqTop[a]);
const out = `// Generated by tools/gen-ranking.mjs (${ITERS} samples per class). Do not edit.
export const EQ_VS_RANDOM = ${JSON.stringify(eqRand.map(x => +x.toFixed(4)))};
export const SHOVE_ORDER = ${JSON.stringify(shoveOrder)};
export const CALL_ORDER = ${JSON.stringify(callOrder)};
`;
writeFileSync(new URL('../site/js/ranking.js', import.meta.url), out);
console.log('top shove:', shoveOrder.slice(0, 20).map(i => CLASS_NAMES[i]).join(' '));
console.log('top call :', callOrder.slice(0, 20).map(i => CLASS_NAMES[i]).join(' '));
console.log('AA eq', eqRand[0], 'AKs', eqRand[1], '72o', eqRand[CLASS_NAMES.indexOf('72o')]);
